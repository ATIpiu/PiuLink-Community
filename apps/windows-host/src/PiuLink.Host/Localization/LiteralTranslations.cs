    private static readonly IReadOnlyDictionary<string, string> SimplifiedChineseReverse =
        SimplifiedChinese
            .GroupBy(entry => entry.Value, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First().Key, StringComparer.Ordinal);

    public static string Translate(string source, string effectiveCode)
    {
        if (string.Equals(effectiveCode, "zh-CN", StringComparison.OrdinalIgnoreCase))
        {
            return SimplifiedChinese.TryGetValue(source, out var translated) ? translated : source;
        }

        return SimplifiedChineseReverse.TryGetValue(source, out var english) ? english : source;
    }
